const LANGUAGE_NAMES = {
  [LANG_EN]: "English",
  [LANG_ZH]: "中文"
};

const LANGUAGE_TOGGLE_LABELS = {
  [LANG_EN]: "中",
  [LANG_ZH]: "EN"
};

function resolveStoredLanguage() {
  if (typeof window === "undefined") {
    return LANG_EN;
  }
  try {
    const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
    if (stored === LANG_ZH || stored === LANG_EN) {
      return stored;
    }
  } catch {
    // ignore storage access failures
  }
  const browserLanguage = String(window.navigator?.language || "");
  if (browserLanguage.toLowerCase().startsWith("zh")) {
    return LANG_ZH;
  }
  return LANG_EN;
}

function formatMessage(template, params = {}) {
  let message = String(template || "");
  for (const [key, value] of Object.entries(params)) {
    message = message.replaceAll(`{${key}}`, String(value ?? ""));
  }
  return message;
}

const I18nContext = createContext({
  lang: LANG_EN,
  setLang: () => {},
  toggleLang: () => {},
  t: (key, params) => key
});

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(resolveStoredLanguage);

  const setLang = useCallback((nextLang) => {
    const resolved = nextLang === LANG_ZH ? LANG_ZH : LANG_EN;
    setLangState(resolved);
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, resolved);
    } catch {
      // ignore storage access failures
    }
    if (typeof document !== "undefined") {
      document.documentElement.lang = resolved;
    }
  }, []);

  const toggleLang = useCallback(() => {
    setLangState((current) => {
      const next = current === LANG_ZH ? LANG_EN : LANG_ZH;
      try {
        window.localStorage.setItem(LANG_STORAGE_KEY, next);
      } catch {
        // ignore storage access failures
      }
      if (typeof document !== "undefined") {
        document.documentElement.lang = next;
      }
      return next;
    });
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
    }
  }, [lang]);

  const value = useMemo(() => {
    const dictionary = translations[lang] || translations[LANG_EN];
    return {
      lang,
      setLang,
      toggleLang,
      t: (key, params = {}) => formatMessage(dictionary[key] ?? key, params)
    };
  }, [lang, setLang, toggleLang]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

export function languageName(lang) {
  return LANGUAGE_NAMES[lang] || LANGUAGE_NAMES[LANG_EN];
}

export function languageToggleLabel(lang) {
  return LANGUAGE_TOGGLE_LABELS[lang] || LANGUAGE_TOGGLE_LABELS[LANG_EN];
}
